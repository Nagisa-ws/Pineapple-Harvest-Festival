        n_leaf = 9
        for j in range(n_leaf):                              # rosette leaves (two straight pieces each)
            a, e = 2 * np.pi * j / n_leaf + float(rng.uniform(-0.2, 0.2)), np.radians(float(rng.uniform(48, 72)))
            ln = float(rng.uniform(0.45, 0.70))
            d = np.array([np.cos(e) * np.cos(a), np.cos(e) * np.sin(a), np.sin(e)])
            e2 = e - np.radians(22)
            d2 = np.array([np.cos(e2) * np.cos(a), np.cos(e2) * np.sin(a), np.sin(e2)])
            b0 = np.array([0.04 * np.cos(a), 0.04 * np.sin(a), 0.08])
            b1 = b0 + 0.55 * ln * d
            b2 = b1 + 0.45 * ln * d2
            mat = "leaf_orange" if rng.uniform() < 0.25 else "leaf"
