def vehicle_assets() -> list:
    s = 0.001
    return [f'    <mesh name="{nm}" file="vehicle/{f}.stl" scale="{s} {s} {s}" inertia="shell"/>'
            for nm, f in (("track_teeth_left", "track_guide_teeth_left"), ("track_teeth_right", "track_guide_teeth_right"),
                          ("chassis_wheels", "track_wheels_right"), ("bed", "bed"), ("crate", "basket-v1"))]


def plant_assets(cfg: dict, segments: bool = True) -> list:
    A = []
    used_f, used_c, used_p = set(), set(), set()
    for kd in cfg["realistic"]["kinds"]:
        used_f.add(int(kd["fruit"])); used_c.add(int(kd["crown"])); used_p.add(int(kd["plant"]))
    for f in sorted(used_f):
        A.append(f'    <mesh name="fruit_{f}" file="pineapple/fruit_{f}.stl" inertia="shell"/>')
        A.append(f'    <mesh name="fruit_{f}_col" file="pineapple/fruit_{f}_col.stl"/>')
    for c in sorted(used_c):
        A.append(f'    <mesh name="crown_{c}" file="pineapple/crown_{c}.stl" inertia="shell"/>')
    for p in sorted(used_p):
        info = json.loads((ASSETS / "plants" / f"p{p}.json").read_text())
        for cls in info["static_classes"]:
            A.append(f'    <mesh name="plant{p}_static_{cls}" file="plants/p{p}_static_{cls}.stl" inertia="shell"/>')
        A.append(f'    <mesh name="plant{p}_stem" file="plants/p{p}_stem.stl" inertia="shell"/>')
        if segments:
            for leaf in info["leaves"]:
                for sg in leaf["segments"]:
                    A.append(f'    <mesh name="{sg["mesh"]}" file="plants/leaves/{sg["mesh"]}.stl" inertia="shell"/>')
    return A


def ground_assets() -> list:
    return ['    <mesh name="ground" file="ground/ground.obj" inertia="shell"/>',
            '    <texture name="soil" type="2d" file="ground/soil.png"/>',
            '    <material name="soil" texture="soil" specular="0.05" reflectance="0.0"/>']


def detail_floor() -> str:
    return ('    <geom name="floor" size="0 0 0.05" type="plane" rgba="0.35 0.28 0.2 0" contype="1" conaffinity="1" friction="1.0 0.005 0.0001" group="3"/>\n'
            '    <geom name="ground_vis" class="mvis" mesh="ground" material="soil"/>')


def light_floor() -> str:
    return '    <geom name="floor" size="0 0 0.05" type="plane" material="groundplane" contype="1" conaffinity="1" friction="1.0 0.005 0.0001"/>'


# ----------------------------------------------------------------------------- Mission 3 scenes
SENSORS = ['    <force name="wrist_force" site="ft_site"/>', '    <torque name="wrist_torque" site="ft_site"/>']


def pool_size(cfg: dict) -> int:
    return int(cfg["eval_field"]["lod"].get("pool_per_kind", 3))


def build_xgh(cfg: dict, detail: bool) -> tuple[str, dict]:
    arm = arm_xml(cfg, detail, "      ", cfg["xgh"]["base_pos_in_vehicle"])
    meta = dict(mode="xgh_detail" if detail else "xgh_light")
    if detail:
        layout = field_layout(cfg)
        K = pool_size(cfg)
        fill = basket_fill_xml(cfg)
        veh, acts = vehicle_xml(cfg, True, "    ", arm + "\n" + fill)
        pool, eq, slots = pool_slots_xml(cfg, K)
        side = side_rows_layout(cfg, True)
        world = static_plants_xml(cfg, layout) + "\n" + side_rows_detail_xml(cfg, side) + "\n" + pool
        meta.update(side_layout=side)
        floor = detail_floor()
        assets = "\n".join(robot_assets() + vehicle_assets() + plant_assets(cfg) + ground_assets())
        meta.update(layout=layout, pool_per_kind=K, slots=slots, n_plants=len(layout))
        n_slots = len(slots)
    else:
        veh, acts = vehicle_xml(cfg, False, "    ", arm)
        from pinesim.model.builder import field_positions
        pos = field_positions(cfg)
        world, eq = plants_xml(cfg, len(pos), pos)
        side = side_rows_layout(cfg, False)
        world = world + "\n" + side_rows_light_xml(cfg, side)
        meta.update(side_layout=side)
        floor = light_floor()
        assets = ""
        meta.update(n_plants=len(pos), plant_xy=pos)
        n_slots = len(pos)
    acts = arm_actuators_u(cfg) + acts
    xml = header_xgh(meta["mode"], cfg, detail, assets) + f"""
  <worldbody>
    <light name="sun" pos="4 -3 6" dir="-0.2 0.3 -1" directional="true" diffuse="0.85 0.85 0.8" specular="0.2 0.2 0.2" castshadow="false"/>
{floor}
{veh}
{world}
  </worldbody>
  <contact>
    <exclude body1="base" body2="shoulder_link"/>
  </contact>
  <equality>
    <joint name="jaw_coupling" joint1="finger_right_joint" joint2="finger_left_joint" polycoef="0 1 0 0 0" solref="0.004 1"/>
{eq}
  </equality>
  <actuator>
{chr(10).join(acts)}
  </actuator>
  <sensor>
{chr(10).join(SENSORS + ['    <framepos name="vehicle_pos" objtype="site" objname="vehicle_origin"/>'])}
  </sensor>
</mujoco>
"""
    meta["n_slots"] = n_slots
    meta["wheel_radius"] = cfg["xgh"]["wheel_radius"]
    meta["n_wheels_per_side"] = len(cfg["xgh"]["wheels_x"])
    meta["base_pos_in_vehicle"] = cfg["xgh"]["base_pos_in_vehicle"]
    return xml, meta


# ----------------------------------------------------------------------------- Missions 1-2 scenes
def build_platform_u(cfg: dict, n_plants: int, detail: bool) -> tuple[str, dict]:
    """UR10e + U-jaw on a column (top = robot.base_mount_height), basket on its own stand (moved by the env to
    180 deg from the plants). Light: procedural plant slots. Detail: per-leaf mesh plant slots (5 kinds x n_plants),
    robot / gripper meshes, ground mesh."""
    rb = cfg["robot"]
    mount = rb["base_mount_height"]
    ph = cfg["platform"]["half_size"]
    arm = arm_xml(cfg, detail, "    ", [0.0, 0.0, mount])
    b = cfg["basket"]
    floor_z = b["floor_height_platform"]
    ft = b.get("floor_thickness", 0.04)
    basket = [f'    <body name="basket" pos="{_f(-b["radius_platform"])} 0 0">',
              f'      <geom name="basket_stand" class="envshow" type="cylinder" size="0.03 {_f((floor_z - ft) / 2 - 0.005)}" '
              f'pos="0 0 {_f((floor_z - ft) / 2 - 0.005)}" material="steel"/>']
    for g in basket_geoms(cfg, 0.0, 0.0, floor_z, "      "):
        basket.append(g.replace('class="envnoleaf"', 'class="envshow"'))
    basket.append('    </body>')
    meta = dict(mode="platform_detail" if detail else "platform", n_plants=n_plants,
                base_pos=[0.0, 0.0, mount])
    if detail:
        plants, eq, slots = pool_slots_xml(cfg, max(1, n_plants))
        floor = detail_floor()
        assets = "\n".join(robot_assets() + plant_assets(cfg) + ground_assets())
        meta.update(slots=slots, n_slots=len(slots))
    else:
        plants, eq = plants_xml(cfg, n_plants)
        floor = light_floor()
        assets = ""
        meta["n_slots"] = n_plants
    xml = header_xgh(meta["mode"], cfg, detail, assets) + f"""
  <worldbody>
    <light name="sun" pos="1 -1 4" dir="-0.2 0.3 -1" directional="true" diffuse="0.85 0.85 0.8" specular="0.2 0.2 0.2" castshadow="false"/>
{floor}
    <geom name="platform" class="envshow" type="box" size="{_f(ph[0])} {_f(ph[1])} {_f(mount / 2)}" pos="0 0 {_f(mount / 2)}" material="steel"/>
    <site name="platform_top" pos="0 0 {_f(mount)}" size="0.01" group="4"/>
{chr(10).join(lamp_xml(cfg, [ph[0] - 0.035, -(ph[1] - 0.035), mount + 0.022], 0.022, "    "))}
    <camera name="overview" pos="1.9 -1.9 1.9" xyaxes="0.707 0.707 0 -0.38 0.38 0.84" fovy="55"/>
{arm}
{chr(10).join(basket)}
{plants}
  </worldbody>
  <contact>
    <exclude body1="base" body2="shoulder_link"/>
  </contact>
  <equality>
    <joint name="jaw_coupling" joint1="finger_right_joint" joint2="finger_left_joint" polycoef="0 1 0 0 0" solref="0.004 1"/>
{eq}
  </equality>
  <actuator>
{chr(10).join(arm_actuators_u(cfg))}
  </actuator>
  <sensor>
{chr(10).join(SENSORS)}
  </sensor>
</mujoco>
"""
    return xml, meta


# ----------------------------------------------------------------------------- pretraining rig
def build_rig_real(cfg: dict) -> tuple[str, dict]:
    """Pretraining rig with the REALISTIC pineapples: one static (mocap) body per plant mesh, fruit mesh and crown
    mesh; the rig shows one combination at a time (5 x 5 x 5), tilted and at a fruit height of 0.60-0.70 m. A camera on
    a pole orbits it (two mocap bodies). Ground mesh around it. No robot, no physics on the plant."""
    from pinesim.model.builder import build_rig_pole
    summ = json.loads((ASSETS / "summary.json").read_text())
    L = []
    for p in range(1, 6):
        info = json.loads((ASSETS / "plants" / f"p{p}.json").read_text())
        L.append(f'    <body name="rplant{p}" mocap="true" pos="0 0 -10">')
        for cls in info["static_classes"]:
            L.append(f'      <geom name="rplant{p}_{cls}" class="mvis" mesh="plant{p}_static_{cls}" rgba="{_class_rgba(info, cls)}"/>')
        L.append('    </body>')
    for f in range(1, 6):
        L.append(f'    <body name="rfruit{f}" mocap="true" pos="0 0 -10">')
        L.append(f'      <geom name="rfruit{f}_vis" class="mvis" mesh="fruit_{f}" rgba="{_rgba(summ[f"fruit_{f}"]["mean_color"])}"/>')
        # peduncle on the fruit body (fixed length, so the Meshcat recording shows it exactly as MuJoCo does)
        L.append(f'      <geom name="rfruit{f}_peduncle" class="pvis" type="cylinder" fromto="0 0 0.01 0 0 -0.38" size="0.016" rgba="{PEDUNCLE_RGBA}"/>')
        L.append('    </body>')
    for c in range(1, 6):
        L.append(f'    <body name="rcrown{c}" mocap="true" pos="0 0 -10">')
        L.append(f'      <geom name="rcrown{c}_vis" class="mvis" mesh="crown_{c}" rgba="{_rgba(summ[f"crown_{c}"]["mean_color"])}"/>')
        L.append('    </body>')
    # assets: all 5 plants (rest-pose class meshes + stems), fruits, crowns
    A = []
    for p in range(1, 6):
        info = json.loads((ASSETS / "plants" / f"p{p}.json").read_text())
        for cls in info["static_classes"]:
            A.append(f'    <mesh name="plant{p}_static_{cls}" file="plants/p{p}_static_{cls}.stl" inertia="shell"/>')
    for f in range(1, 6):
        A.append(f'    <mesh name="fruit_{f}" file="pineapple/fruit_{f}.stl" inertia="shell"/>')
    for c in range(1, 6):
        A.append(f'    <mesh name="crown_{c}" file="pineapple/crown_{c}.stl" inertia="shell"/>')
    A += ground_assets()
    xml = header_xgh("stargaze_rig_real", cfg, True, "\n".join(A)) + f"""
  <worldbody>
    <light name="sun" pos="1 -1 4" dir="-0.2 0.3 -1" directional="true" diffuse="0.85 0.85 0.8" specular="0.2 0.2 0.2" castshadow="false"/>
{detail_floor()}
{build_rig_pole(cfg, lamp=True)}
{chr(10).join(L)}
  </worldbody>
</mujoco>
"""
    return xml, dict(mode="rig")
