def field_layout(cfg: dict) -> list:
    """Plants of the 15 m evaluation field: position, kind, yaw, tilt (0-15 deg, any direction), stem strength.
    Kinds are assigned so that no plant has the same kind as a neighbour (in its row or across the zig-zag)."""
    ef = cfg["eval_field"]
    rng = np.random.default_rng(int(ef["seed"]))
    n, x0 = int(ef["plants_per_row"]), float(ef["first_plant_x"])
    sp, st, oy = (float(cfg["field"].get("plant_spacing", 0.50)), float(cfg["field"].get("row_stagger", 0.25)),
                  float(cfg["field"].get("row_offset_y", 0.15)))
    pts = []
    for k in range(n):
        pts.append((x0 + k * sp, +oy))
        pts.append((x0 + st + k * sp, -oy))
    pts.sort(key=lambda p: p[0])
    nk = len(cfg["realistic"]["kinds"])
    kinds = []
    for j, (x, y) in enumerate(pts):
        bad = {kinds[i] for i in range(len(kinds)) if np.hypot(pts[i][0] - x, pts[i][1] - y) < 0.65}
        options = [k for k in range(nk) if k not in bad] or list(range(nk))
        kinds.append(int(rng.choice(options)))
    rc = cfg["realistic"]
    bf, bt = rc["stem_break_force_range"], rc["stem_break_torque_range"]
    t0, t1 = np.radians(cfg["plant"].get("tilt_deg_range", [0.0, 15.0]))
    out = []
    for j, (x, y) in enumerate(pts):
        out.append(dict(index=j, x=float(x), y=float(y), kind=kinds[j], yaw=float(rng.uniform(0, 2 * np.pi)),
                        fruit_yaw=float(rng.uniform(0, 2 * np.pi)), break_force=float(rng.uniform(*bf)),
                        break_torque=float(rng.uniform(*bt)), tilt=float(rng.uniform(t0, t1)),
                        tilt_az=float(rng.uniform(0, 2 * np.pi))))
    return out


