        for j in range(4):                                   # crown tufts
            a, e = j * np.pi / 2 + 0.4, np.radians(65)
            d = np.array([np.cos(e) * np.cos(a), np.cos(e) * np.sin(a), np.sin(e)])
            b0, b1 = np.array([0, 0, zc + hh]), np.array([0, 0, zc + hh]) + 0.13 * d
