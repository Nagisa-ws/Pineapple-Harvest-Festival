# ----------------------------------------------------------------------------- small math
def quat_yaw(a: float) -> np.ndarray:
    return np.array([math.cos(a / 2), 0.0, 0.0, math.sin(a / 2)])


def quat_tilt(angle: float, azimuth: float) -> np.ndarray:
    """Rotation by `angle` about the horizontal axis at `azimuth` (plant leaning toward azimuth + 90 deg)."""
    s = math.sin(angle / 2)
    return np.array([math.cos(angle / 2), s * math.cos(azimuth), s * math.sin(azimuth), 0.0])


def quat_mul(a, b) -> np.ndarray:
    w1, x1, y1, z1 = a
    w2, x2, y2, z2 = b
    return np.array([w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2, w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2,
                     w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2, w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2])


def plant_quat(p: dict) -> np.ndarray:
    """World orientation of a field plant: yaw about its own axis, then the tilt."""
    return quat_mul(quat_tilt(p.get("tilt", 0.0), p.get("tilt_az", 0.0)), quat_yaw(p.get("yaw", 0.0)))


