def side_rows_layout(cfg: dict, detail: bool) -> list:
    """[USER v6] Neighbour beds left and right of the bed being harvested (Mission 3): STATIC, non-interactive plants
    (visual only - no joints, no collision). `field.side_rows.edge_gap` = distance between the edge of this bed and
    the edge of the neighbour bed, where an edge is the centre line of the bed's outer plant row (the two rows of a
    bed are `2 * field.row_offset_y` apart). Same plant spacing and zig-zag as the harvested bed."""
    f = cfg["field"]
    sr = dict(f.get("side_rows") or {})
    if not sr.get("enabled", False):
        return []
    gap, nb, extra = float(sr.get("edge_gap", 0.50)), int(sr.get("beds_per_side", 1)), int(sr.get("extra_plants", 1))
    sp, st, oy = float(f.get("plant_spacing", 0.50)), float(f.get("row_stagger", 0.25)), float(f.get("row_offset_y", 0.15))
    if detail:
        ef = cfg["eval_field"]
        n, x0, seed = int(ef["plants_per_row"]), float(ef["first_plant_x"]), int(ef["seed"]) + 101
    else:
        n, x0, seed = int(f["plants_per_row"]), float(f["first_plant_x"]), 101
    rng = np.random.default_rng(seed)
    nk = len(cfg["realistic"]["kinds"])
    t0, t1 = np.radians(cfg["plant"].get("tilt_deg_range", [0.0, 15.0]))
    out = []
    for side in (+1.0, -1.0):
        for b in range(nb):
            y_near = oy + gap + b * (2 * oy + gap)             # nearest plant row of neighbour bed b
            for k in range(-extra, n + extra):
                for x, y in ((x0 + k * sp, side * y_near), (x0 + st + k * sp, side * (y_near + 2 * oy))):
                    out.append(dict(index=len(out), x=float(x), y=float(y), kind=int(rng.integers(nk)),
                                    yaw=float(rng.uniform(0, 2 * np.pi)), fruit_yaw=float(rng.uniform(0, 2 * np.pi)),
                                    tilt=float(rng.uniform(t0, t1)), tilt_az=float(rng.uniform(0, 2 * np.pi)),
                                    side="L" if side > 0 else "R", bed=b))
    return out


