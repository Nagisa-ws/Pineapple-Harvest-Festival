        zc = float(rng.uniform(*cfg["plant"]["fruit"]["center_height_range"]))
        r = 0.5 * float(rng.uniform(*cfg["plant"]["fruit"]["diameter_range"]))
        hh = 0.5 * float(rng.uniform(*cfg["plant"]["fruit"]["height_range"]))
